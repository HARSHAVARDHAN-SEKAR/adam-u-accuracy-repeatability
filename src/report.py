#!/usr/bin/env python3
"""
report.py -- write results/report.md from the raw results.

    python3 src/report.py

The report is generated: every number in it is read from results/summary.json
(which is rebuilt from the raw CSV files first), so it always matches the run
that is on disk.
"""
from __future__ import annotations

import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from src.analysis import build_summary  # noqa: E402
from src.experiment import REPO_ROOT, load_config  # noqa: E402

MODE = {"pd": "PD only", "pd_gff": "PD + gravity FF"}
JOINTS = ["waist", "shoulderPitch", "shoulderRoll", "shoulderYaw", "elbow", "wristYaw", "wristPitch", "wristRoll"]


def f(v, digits=3):
    return f"{v:.{digits}f}"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def group_table(groups):
    header = ["Control", "Plant condition", "Trials", "AP mean (mm)", "AP max (mm)", "RP mean (mm)", "RP max (mm)",
              "vAP max (mm)", "Orientation error mean (deg)", "Within tolerance"]
    rows = [[MODE[g["control_mode"]], g["condition"], g["n_trials"], f(g["AP_mean_mm"]), f(g["AP_max_mm"]),
             f(g["RP_mean_mm"], 4), f(g["RP_max_mm"], 4), f(g["vAP_max_mm"]), f(g["ori_err_mean_deg"]),
             f"{100 * g['success_rate']:.0f} %"] for g in groups]
    return table(header, rows)


def classic_table(groups):
    header = ["Control", "Plant condition", "Trials", "Mean error (mm)", "Spread, 1 SD (mm)", "RMSE (mm)",
              "Worst case (mm)", "Success rate"]
    rows = [[MODE[g["control_mode"]], g["condition"], g["n_trials"], f(g["mean_error_mm"]),
             f(g["error_spread_mm"], 4), f(g["pos_err_rmse_mm"]), f(g["pos_err_max_mm"]),
             f"{100 * g['success_rate']:.0f} %"] for g in groups]
    return table(header, rows)


def build_report(summary: dict, cfg: dict) -> str:
    main = summary["main"]
    info = main.get("run_info", {})
    proto, design, tol = cfg["protocol"], cfg["design"], summary["tolerance"]
    by = {(g["control_mode"], g["condition"]): g for g in main["groups"]}
    L = []
    L.append("# ADAM-U TCP accuracy and repeatability: results report\n")
    L.append("_Generated by `src/report.py` from `results/raw_trials.csv` and `results/raw_ablation.csv`. "
             "Do not edit by hand; re-run the script._\n")
    L.append(table(["Run", ""], [
        ["Written", info.get("written", "?")],
        ["MuJoCo", info.get("mujoco_version", "?")],
        ["pnd_mujoco commit", f"`{info.get('pnd_mujoco_commit_found', '?')}`"],
        ["Trials", info.get("n_trials", "?")],
        ["Seed", info.get("seed", "?")],
        ["Simulated time per trial", f"{proto['pre_hold_s'] + proto['move_s'] + proto['dwell_s']:.1f} s "
                                     f"({proto['pre_hold_s']} hold + {proto['move_s']} move + {proto['dwell_s']} dwell)"],
    ]))

    L.append("\n## 1. Definitions\n")
    L.append("- **AP, position accuracy**: distance from the commanded TCP position to the mean of the reached "
             "positions (ISO 9283 definition).\n"
             "- **RP, position repeatability**: mean distance of the reached positions from their own mean, "
             "plus three standard deviations (ISO 9283 definition).\n"
             "- **vAP**: distance between the mean positions reached from the two approach directions.\n"
             f"- A *cell* is one target reached from one approach direction, {design['repetitions']} repetitions. "
             "AP and RP are computed per cell; the tables give their mean and maximum over the 10 cells.\n"
             f"- *Within tolerance* uses {tol['position_mm']} mm and {tol['orientation_deg']} deg, "
             "declared in the config for illustration.\n"
             "- The TCP pose is read from the simulator (ground truth).")

    L.append("\n## 2. Main experiment\n")
    L.append("### 2.1 ISO-style metrics\n")
    L.append(group_table(main["groups"]))
    L.append("\n### 2.2 Classic error metrics\n")
    L.append("The same 400 trials summarised the usual way: statistics of the per-trial distance from the "
             "commanded position. These answer a different question from AP and RP -- see section 2.3.\n")
    L.append(classic_table(main["groups"]))
    L.append("\n### 2.3 Why both sets are reported\n")
    L.append("- **Mean error** does not cancel opposing errors, **AP** does. Two trials 5 mm either side of the "
             "target give mean error 5 mm and AP 0 mm. Mean error is therefore never smaller than AP, and the gap "
             "between them tells you how much of the error is scatter rather than bias.\n"
             "- **Spread** (standard deviation of the error magnitudes) is not spatial scatter. Points spread over "
             "the surface of a sphere centred on the target all have the same error magnitude: spread 0, while "
             "**RP** correctly reports them as far apart. RP measures distance from the cluster's own centre in "
             "three dimensions; spread measures variation of a single scalar.\n"
             "- **RMSE** weights outliers more heavily than the mean. With these results the two are close, which "
             "is itself informative: the error distribution has no long tail.\n"
             "- **Success rate** collapses everything to one bit per trial against the declared tolerance "
             f"({tol['position_mm']} mm, {tol['orientation_deg']} deg). It is the easiest number to quote and the "
             "easiest to game by choosing a generous tolerance, so it is reported alongside the others, never "
             "alone.\n")
    gaps = [(MODE[g["control_mode"]] + " / " + g["condition"], g["mean_error_mm"] - g["AP_mean_mm"])
            for g in main["groups"]]
    worst_label, worst_gap = max(gaps, key=lambda kv: abs(kv[1]))
    gap_txt = f"{abs(worst_gap):.3f}" if abs(worst_gap) >= 5e-4 else f"{abs(worst_gap):.1e}"
    L.append(f"\nIn this run mean error and AP agree to within {gap_txt} mm (largest gap: "
             f"{worst_label}). That is the measurement talking: the two can only coincide when the trials of a "
             "cell land on top of each other, which is exactly what the near-zero RP columns say. Every "
             "millimetre of error here is systematic bias, not scatter -- so the robot is not imprecise, it is "
             "mis-aimed, and the fix is calibration or a better controller model rather than better hardware "
             "repeatability.")
    L.append("\n### 2.4 Distribution, spread, orientation and operation\n")
    L.append("Per-trial position error (all trials of a group pooled):\n")
    L.append(table(["Control", "Plant condition", "Median (mm)", "90th percentile (mm)", "95th percentile (mm)",
                    "Worst (mm)"],
                   [[MODE[g["control_mode"]], g["condition"], f(g["pos_err_p50_mm"]), f(g["pos_err_p90_mm"]),
                     f(g["pos_err_p95_mm"]), f(g["pos_err_max_mm"])] for g in main["groups"]]))
    L.append("\nScatter of the repeats inside a cell (mean over the 10 cells; largest cell in brackets):\n")
    L.append(table(["Control", "Plant condition", "SD x (mm)", "SD y (mm)", "SD z (mm)", "95 % radius (mm)",
                    "RP, ISO (mm)"],
                   [[MODE[g["control_mode"]], g["condition"]]
                    + [f"{f(g['std_xyz_mean_mm'][i], 4)} ({f(g['std_xyz_max_mm'][i], 4)})" for i in range(3)]
                    + [f"{f(g['radius_p95_mean_mm'], 4)} ({f(g['radius_p95_max_mm'], 4)})",
                       f"{f(g['RP_mean_mm'], 4)} ({f(g['RP_max_mm'], 4)})"] for g in main["groups"]]))
    L.append("\nOrientation error (angle of the single rotation between commanded and reached orientation):\n")
    L.append(table(["Control", "Plant condition", "Mean (deg)", "95th percentile (deg)", "Worst (deg)",
                    "Spread between repeats, 1 SD (deg)"],
                   [[MODE[g["control_mode"]], g["condition"], f(g["ori_err_mean_deg"]), f(g["ori_err_p95_deg"]),
                     f(g["ori_err_max_deg"]),
                     f"{f(g['ori_err_spread_mean_deg'], 4)} (max {f(g['ori_err_spread_max_deg'], 4)})"]
                    for g in main["groups"]]))
    L.append("\nOperation:\n")
    L.append(table(["Control", "Plant condition", "Stabilisation time mean / 95th pct / max (s)",
                    "Peak torque mean / max (% of limit)", "Saturated trials", "Not settled at the measurement",
                    f"Within {tol['position_mm']} mm and {tol['orientation_deg']} deg"],
                   [[MODE[g["control_mode"]], g["condition"],
                     f"{g['stab_time_mean_s']:.2f} / {g['stab_time_p95_s']:.2f} / {g['stab_time_max_s']:.2f}",
                     f"{100 * g['peak_torque_frac_mean']:.0f} / {100 * g['peak_torque_frac_max']:.0f}",
                     g["n_saturated"], g["n_not_settled"], f"{100 * g['success_rate']:.0f} %"]
                    for g in main["groups"]]))
    L.append("\nA trial is *not settled* when the TCP was still outside the "
             f"{proto['stabilisation_band_mm']} mm band at the end of the dwell. The timing is fixed, so there is "
             "no time-out; not settled and saturated are the two ways a trial can be flagged.\n")
    L.append("![error distributions](plots/fig8_error_distributions.png)\n")
    L.append("![repeatability spread](plots/fig10_repeatability_spread.png)\n")
    L.append("![operational](plots/fig9_operational.png)\n")
    L.append("\n![accuracy and repeatability](plots/fig1_accuracy_vs_repeatability.png)\n")
    L.append("![commanded and reached](plots/fig2_commanded_vs_reached.png)\n")

    L.append("\n### Per target\n")
    cells = {(c["control_mode"], c["condition"], c["target"], c["approach"]): c for c in main["cells"]}
    rows = []
    for t in main["targets"]:
        k = (t["control_mode"], t["condition"], t["target"])
        p, m = cells[k + ("plus",)], cells[k + ("minus",)]
        rows.append([MODE[k[0]], k[1], k[2], f(p["AP_mm"]), f(m["AP_mm"]), f(p["RP_mm"], 4), f(m["RP_mm"], 4),
                     f(t["vAP_mm"])])
    L.append(table(["Control", "Plant condition", "Target", "AP, approach plus (mm)", "AP, approach minus (mm)",
                    "RP, plus (mm)", "RP, minus (mm)", "vAP (mm)"], rows))
    L.append("\n![approach clusters](plots/fig3_approach_clusters.png)\n")

    L.append("\n## 3. Checks on the procedure itself\n")
    checks = []
    ideal = by.get(("pd_gff", "nominal"))
    if ideal:
        checks.append(["Measurement floor: ideal plant with exact gravity feed-forward",
                       f"AP mean {f(ideal['AP_mean_mm'], 4)} mm, max {f(ideal['AP_max_mm'], 4)} mm"])
    det = [g for g in main["groups"] if g["condition"] == "nominal"]
    if det:
        checks.append(["Determinism: largest RP over all ideal-plant cells",
                       f"{max(g['RP_max_mm'] for g in det):.2e} mm"])
    for g in main["groups"] + summary.get("ablation", {}).get("groups", []):
        checks.append([f"Simulation minus static prediction, {MODE[g['control_mode']]} / {g['condition']}",
                       f"mean {f(g['resid_after_static_mean_mm'], 4)} mm, max {f(g['resid_after_static_max_mm'], 4)} mm "
                       f"(prediction itself is {f(g['static_pred_err_mean_mm'])} mm from the target)"])
    checks.append(["Longest stabilisation time (TCP inside "
                   f"{proto['stabilisation_band_mm']} mm of its final position)",
                   f"{max(g['stab_time_max_s'] for g in main['groups']):.2f} s of a {proto['dwell_s']} s dwell"])
    checks.append(["Highest joint torque used", f"{100 * max(g['peak_torque_frac_max'] for g in main['groups']):.0f} % "
                   f"of the limit; saturated trials: {sum(g['n_saturated'] for g in main['groups'])}"])
    checks.append(["First-order joint breakdown versus measured error, largest gap",
                   f"{max(g['linearisation_gap_max_mm'] for g in main['groups']):.2f} mm"])
    L.append(table(["Check", "Result"], checks))
    L.append("\nThe static prediction solves `tau_ff + kp (q_cmd - q - offset) = g(q)` for the joint angles without "
             "simulating and pushes them through forward kinematics. It knows about gravity, payload and encoder "
             "offsets, not about friction or noise. Where friction and noise are off, simulation and prediction "
             "should agree to within the floor.")
    L.append("\n![settling](plots/fig6_settling.png)\n")

    if "ablation" in summary:
        ab = summary["ablation"]
        L.append("\n## 4. One error source at a time\n")
        L.append(f"Control mode: {MODE[ab['groups'][0]['control_mode']]}. "
                 f"{ab['groups'][0]['n_trials']} trials per row. Every row includes the start-configuration jitter.\n")
        ab_sorted = sorted(ab["groups"], key=lambda g: g["AP_mean_mm"])
        L.append(group_table(ab_sorted))
        L.append("")
        L.append(classic_table(ab_sorted))
        L.append("\n![error sources](plots/fig5_error_sources.png)\n")

    L.append("\n## 5. Which joint the error comes from\n")
    L.append("Mean over trials of |Jacobian column x joint error|, in mm of TCP displacement. "
             "The waist entry combines its three joints.\n")
    rows = [[MODE[g["control_mode"]], g["condition"]] + [f(g["contrib_mean_mm"][j], 2) for j in JOINTS]
            for g in main["groups"]]
    L.append(table(["Control", "Plant condition"] + JOINTS, rows))
    L.append("\n![error by joint](plots/fig4_error_by_joint.png)\n")

    gain_csv = os.path.join(REPO_ROOT, "results", "gain_sensitivity.csv")
    if os.path.isfile(gain_csv):
        import csv
        with open(gain_csv) as fh:
            rows = list(csv.DictReader(fh))
        kps = sorted({float(r["soft_joint_kp"]) for r in rows})
        cases = list(dict.fromkeys((r["control_mode"], r["condition"]) for r in rows))
        val = {(float(r["soft_joint_kp"]), r["control_mode"], r["condition"]): r for r in rows}
        L.append("\n## 6. Gain sensitivity (what-if)\n")
        L.append("The vendor example gives shoulder yaw, elbow and the three wrist joints kp = 9 N·m/rad. "
                 "This run raises that value on those five joints and changes nothing else (kd scaled with "
                 "sqrt(kp), one trial per target and approach). It measures how much of the error is the choice "
                 "of gains. It is not a tuning proposal: stability on hardware was not examined.\n")
        L.append(table(["kp of the five soft joints"] + [f"{MODE[m]}, {c} (mm)" for m, c in cases],
                       [[f"{kp:g}"] + [f(float(val[(kp, m, c)]["mean_error_mm"])) for m, c in cases] for kp in kps]))
        gap = max(abs(float(r["mean_error_mm"]) - float(r["static_prediction_mm"])) for r in rows
                  if r["condition"] == "nominal")
        lo, hi = kps[0], kps[-1]
        pd0, pd1 = (float(val[(k, "pd", "nominal")]["mean_error_mm"]) for k in (lo, hi))
        ff0, ff1 = (float(val[(k, "pd_gff", "perturbed")]["mean_error_mm"]) for k in (lo, hi))
        L.append(f"\n- Without feed-forward, a {hi / lo:.0f}-fold stiffer setting reduces the ideal-plant error "
                 f"from {pd0:.0f} to {pd1:.0f} mm, a factor of {pd0 / pd1:.1f}. It levels off because the "
                 "shoulder pitch, shoulder roll and waist joints, which were not changed, still sag.\n"
                 f"- With feed-forward on the perturbed plant the error falls from {ff0:.1f} to {ff1:.1f} mm: "
                 "what feed-forward cannot cancel (the unknown payload) is divided by the stiffness.\n"
                 f"- On the ideal plant the simulated error matches the static prediction within {gap:.3f} mm at "
                 "every gain, so the relation error = unmodelled torque / kp holds across the range.\n"
                 f"- Longest stabilisation time in this run: "
                 f"{max(float(r['stab_time_max_s']) for r in rows):.2f} s; highest torque used: "
                 f"{100 * max(float(r['peak_torque_frac_max']) for r in rows):.0f} % of the limit.")
        L.append("\n![gain sensitivity](plots/fig7_gain_sensitivity.png)\n")

    L.append("\n## 7. Plant conditions used\n")
    L.append("```yaml\n" + "\n".join(
        f"{name}: {json.dumps(cfg['conditions'][name])}" for name in
        list(dict.fromkeys(design["conditions"] + design["ablation_conditions"]))) + "\n```")
    L.append("\nThese magnitudes are assumptions. They were not identified on a real ADAM-U.")
    return "\n".join(L) + "\n"


def main():
    results_dir = os.path.join(REPO_ROOT, "results")
    summary = build_summary(results_dir)
    with open(os.path.join(results_dir, "summary.json"), "w") as fh:
        json.dump(summary, fh, indent=2)
    path = os.path.join(results_dir, "report.md")
    with open(path, "w") as fh:
        fh.write(build_report(summary, load_config()))
    print("wrote", os.path.relpath(path, REPO_ROOT))


if __name__ == "__main__":
    main()
